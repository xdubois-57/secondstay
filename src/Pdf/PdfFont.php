 * Une des polices standard du format PDF, avec sa table de largeurs.
 *
 * Les quatorze polices standard sont présentes dans tout lecteur : ne pas
 * embarquer de fichier de police garde les contrats à quelques kilo-octets et
 * évite d'ajouter une dépendance ou une licence à un hébergement mutualisé.
 *
 * Le codage retenu est `WinAnsiEncoding`, qui couvre l'intégralité des
 * caractères du français, du néerlandais et de l'allemand — accents, ß, ligature
 * œ exceptée — ainsi que l'euro, les guillemets et l'apostrophe typographique.
