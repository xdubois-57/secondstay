enum PdfFont: string
{
    case Regular = 'Helvetica';
    case Bold = 'Helvetica-Bold';
    case Italic = 'Helvetica-Oblique';

    /**
     * Largeur d'un caractère, en millièmes de la taille de police.
     *
     * Les valeurs proviennent des métriques AFM publiées avec le format : sans
     * elles, aucun retour à la ligne ne peut être calculé correctement.
     *
     * @return array<int, int>
     */
    public function widths(): array
    {
        return $this === self::Bold ? self::boldWidths() : self::regularWidths();
    }

    public function resourceName(): string
    {
        return match ($this) {
            self::Regular => 'F1',
            self::Bold => 'F2',
            self::Italic => 'F3',
        };
    }

    /**
     * Largeur d'une chaîne déjà encodée en WinAnsi, en millièmes.
     */
    public function widthOf(string $encoded): int
    {
        $widths = $this->widths();
        $total = 0;

        for ($index = 0, $length = strlen($encoded); $index < $length; $index++) {
            $total += $widths[ord($encoded[$index])] ?? 500;
        }

        return $total;
    }

